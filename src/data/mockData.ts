// Architecture guidelines text representations
export const POSTGRESQL_SCHEMA_SQL = `-- 1. Tabla de Usuarios y Billetera
CREATE TABLE users (
   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
   email VARCHAR(255) UNIQUE NOT NULL,
   username VARCHAR(50) UNIQUE NOT NULL,
   role VARCHAR(20) DEFAULT 'CLIENT' CHECK (role IN ('CLIENT', 'MODERATOR', 'ADMIN')),
   wallet_balance_usd NUMERIC(10, 2) DEFAULT 0.00 CHECK (wallet_balance_usd >= 0),
   is_banned BOOLEAN DEFAULT FALSE,
   created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Paquetes de Videojuegos
CREATE TABLE game_packages (
   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
   game_slug VARCHAR(50) NOT NULL, -- 'free-fire', 'mlbb', 'codm'
   name VARCHAR(100) NOT NULL, -- '100 + 10 Diamantes'
   price_usd NUMERIC(10, 2) NOT NULL,
   cost_usd NUMERIC(10, 2) NOT NULL, -- Costo mayorista
   delivery_method VARCHAR(30) NOT NULL CHECK (delivery_method IN ('BOT_ID_SCRAPE', 'PIN_INVENTORY', 'OPERATOR_ASSISTED')),
   is_active BOOLEAN DEFAULT TRUE
);

-- 3. Pedidos y Transacciones de Recarga
CREATE TABLE orders (
   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
   user_id UUID REFERENCES users(id) ON DELETE SET NULL,
   package_id UUID REFERENCES game_packages(id),
   target_player_id VARCHAR(100) NOT NULL,
   target_zone_id VARCHAR(50),
   verified_nickname VARCHAR(100) NOT NULL, -- Nickname verificado antes de pagar
   amount_usd NUMERIC(10, 2) NOT NULL,
   payment_method VARCHAR(50) NOT NULL CHECK (payment_method IN ('PAGO_MOVIL', 'BINANCE_PAY', 'WALLET')),
   payment_reference VARCHAR(150),
   payment_receipt_url TEXT,
   payment_status VARCHAR(30) DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
   fulfillment_status VARCHAR(30) DEFAULT 'QUEUED' CHECK (fulfillment_status IN ('QUEUED', 'PROCESSING_BOT', 'COMPLETED', 'FAILED_RETRY', 'MANUAL_REQUIRED')),
   bot_attempts INT DEFAULT 0,
   bot_log TEXT,
   operator_id UUID REFERENCES users(id),
   created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
   updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Códigos Gift Cards (Inventario Instantáneo)
CREATE TABLE gift_cards (
   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
   game_slug VARCHAR(50) NOT NULL,
   code_encrypted TEXT NOT NULL,
   face_value_usd NUMERIC(10, 2) NOT NULL,
   is_redeemed BOOLEAN DEFAULT FALSE,
   order_id UUID REFERENCES orders(id),
   redeemed_at TIMESTAMP WITH TIME ZONE
);

-- 5. Torneos y Participantes
CREATE TABLE tournaments (
   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
   title VARCHAR(150) NOT NULL,
   game_slug VARCHAR(50) NOT NULL,
   format VARCHAR(50) NOT NULL CHECK (format IN ('BATTLE_ROYALE', 'SINGLE_ELIMINATION', 'DOUBLE_ELIMINATION')),
   entry_fee_usd NUMERIC(10, 2) DEFAULT 0.00,
   prize_pool_usd NUMERIC(10, 2) NOT NULL,
   max_teams INT NOT NULL,
   room_id VARCHAR(100),
   room_password VARCHAR(100),
   check_in_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
   start_time TIMESTAMP WITH TIME ZONE NOT NULL,
   status VARCHAR(30) DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CHECK_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
   created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);`;
